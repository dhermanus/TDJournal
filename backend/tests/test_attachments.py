def test_deleting_a_trade_removes_its_files(client):
    meta = upload(client, name="chart.png").json()
    path = stored_path(client.uploads, meta["stored_name"])
    trade_id = client.trade_id

    assert client.delete(f"/api/trades/{trade_id}").status_code == 200
    assert not path.exists()
    assert client.get(f"/api/trades/{client.group}/attachments").status_code == 404


def test_other_trades_keep_their_files_when_one_is_deleted(client):
    mine = upload(client, name="mine.png").json()
    theirs = upload(client, group=client.other_group, name="theirs.png").json()
    trade_id = client.trade_id

    client.delete(f"/api/trades/{trade_id}")

    assert stored_path(client.uploads, theirs["stored_name"]).is_file()
    assert not stored_path(client.uploads, mine["stored_name"]).exists()
    assert [a["id"] for a in
            client.get(f"/api/trades/{client.other_group}/attachments").json()["attachments"]] == [theirs["id"]]


def test_a_tampered_row_cannot_point_the_download_outside_uploads(client, tmp_path):
    """Rows are data, not paths: a stored_name of '../../x' must not read it."""
    secret = tmp_path / "secret.env"
    secret.write_text("API_KEY=nope")
    meta = upload(client, name="chart.png").json()

    conn = sqlite3.connect(client.db)
    conn.execute("UPDATE trade_attachments SET stored_name='../../secret.env' WHERE id=?",
                 (meta["id"],))
    conn.commit()
    conn.close()

    r = client.get(f"/api/attachments/{meta['id']}/download")
    assert r.status_code == 404
    assert "missing" in r.json()["error"]
    assert b"API_KEY" not in r.content


def test_a_tampered_row_with_an_absolute_path_is_refused(client):
    meta = upload(client, name="chart.png").json()
    conn = sqlite3.connect(client.db)
    conn.execute("UPDATE trade_attachments SET stored_name='/etc/passwd' WHERE id=?",
                 (meta["id"],))
    conn.commit()
    conn.close()
    assert client.get(f"/api/attachments/{meta['id']}/download").status_code == 404


def test_init_db_repairs_early_account_scoped_attachment_table_without_losing_rows(client):
    """Converge the earlier NOT NULL account_id draft and preserve metadata."""
    import database

    db = client.db
    stored = upload(client, name="keep-me.png", content=b"retained").json()
    conn = sqlite3.connect(db)
    conn.execute("ALTER TABLE trade_attachments ADD COLUMN account_id INTEGER NOT NULL DEFAULT 1")
    conn.commit()
    conn.close()

    database.DB_PATH = db
    database.init_db()
    database.init_db()  # repair and ordinary init must both be repeatable

    conn = sqlite3.connect(db)
    conn.row_factory = sqlite3.Row
    cols = [r["name"] for r in conn.execute("PRAGMA table_info(trade_attachments)")]
    row = conn.execute("SELECT * FROM trade_attachments WHERE id=?", (stored["id"],)).fetchone()
    conn.close()

    assert "account_id" not in cols
    assert row["stored_name"] == stored["stored_name"]
    assert row["original_name"] == "keep-me.png"
    assert stored_path(client.uploads, stored["stored_name"]).read_bytes() == b"retained"

    # Fresh inserts match the live pre-fix failure mode and no longer require an account_id.
    conn = sqlite3.connect(db)
    conn.row_factory = sqlite3.Row
    meta = attachments.save(conn, upload_dir=client.uploads, trade_group=client.group,
                            filename="after-repair.png", content_type="image/png", raw=b"new")
    conn.close()
    assert meta["original_name"] == "after-repair.png"
    assert stored_path(client.uploads, meta["stored_name"]).read_bytes() == b"new"


def test_init_db_on_a_pre_existing_database_adds_the_table(client):
    """The migration shape used by this tree: idempotent DDL, rows survive."""
    db = client.db
    conn = sqlite3.connect(db)
    conn.execute("DROP TABLE trade_attachments")
    conn.commit()
    conn.close()

    import database
    database.DB_PATH = db
    database.init_db()          # run twice: it must be a no-op the second time
    database.init_db()

    conn = sqlite3.connect(db)
    names = [r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")]
    conn.close()
    assert "trade_attachments" in names


def test_list_is_ordered_oldest_first(client):
    ids = [upload(client, name=f"{i}.png", content=bytes([i + 65])).json()["id"]
           for i in range(3)]
